// Agents gate.
import { chromium, BASE, ok, summary, errors, login, settle } from './lib.mjs';
const b = await chromium.launch();
const p = await login(b, 'admin', '', { width: 1366, height: 900 });
const fail = (pattern, msg) => p.route(pattern, (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: msg }) }));
const txt = async (sel) => (await p.locator(sel).first().textContent().catch(() => '')) || '';
await p.goto(`${BASE}/agents?range=21600`); await settle(p, 2000);
const rows = await p.locator('#main tbody tr').count();
ok(rows > 0, `fleet: ${rows} agents`);
await p.fill('#main input[aria-label="Filter agents"]', 'zz-none'); await settle(p, 300);
ok(/q=zz-none/.test(p.url()) && /No agent matches/.test(await txt('#main tbody')), 'filter in URL + no-match message');
await p.click('#main tbody button:has-text("Clear filter")'); await settle(p, 300);
ok(await p.locator('#main tbody tr').count() === rows, 'Clear filter restores the list');
await p.click('.tabs >> text=Install'); await settle(p, 500);
ok(/tab=install/.test(p.url()) && /range=21600/.test(p.url()), 'tab in URL with range');
await p.click('.tabs >> text=Fleet'); await settle(p, 500);
await p.waitForTimeout(6000);
await fail('**/api/agents', 'Database busy');
await p.click('#refresh-btn'); await settle(p, 800);
ok(await p.locator('#main tbody tr').count() === rows && /Couldn't refresh/.test(await txt('.stale-notice')), 'refresh failure: kept + stale notice');
await p.goto(`${BASE}/agents`); await settle(p, 1500);
ok(await p.locator('[role=alert]:has-text("Database busy")').count() === 1 && await p.locator('#main button:has-text("Try again")').count() === 1, 'first-load failure: cause + Try again');
await p.unroute('**/api/agents');
await p.click('#main button:has-text("Try again")'); await settle(p, 1800);
ok(await p.locator('#main tbody tr').count() === rows, 'Try again recovers');
await p.click('.tabs >> text=Tokens'); await settle(p, 1500);
ok(await p.locator('#main table').count() === 1 || /No tokens yet/.test(await txt('#main')), 'tokens tab loads');
await p.setViewportSize({ width: 390, height: 844 }); await p.goto(`${BASE}/agents`); await settle(p, 2000);
const fit = await p.evaluate(() => [...document.querySelectorAll('.table-wrap')].every((w) => w.scrollWidth <= w.clientWidth + 1) && document.documentElement.scrollWidth <= 391);
ok(fit, '390px: fleet table fits');
ok(!/null|undefined/.test(await p.locator('#main').innerText()), 'no stray null text');
ok(!errors.length, `no page errors ${errors.join(' | ')}`);
summary();
await b.close();
