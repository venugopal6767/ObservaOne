// Alert Rules gate.
import { chromium, BASE, ok, summary, errors, login, settle } from './lib.mjs';
const b = await chromium.launch();
const p = await login(b, 'admin', '', { width: 1366, height: 900 });
const fail = (pattern, msg) => p.route(pattern, (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: msg }) }));
const txt = async (sel) => (await p.locator(sel).first().textContent().catch(() => '')) || '';
await p.goto(`${BASE}/alerting?range=21600`); await settle(p, 2000);
ok(await txt('#main h1') === 'Alert Rules' && await p.locator('.nav-item.active').getAttribute('aria-label') === 'Alert Rules', 'page title matches the menu item');
const editable = await p.evaluate(async () => (await (await fetch('/api/rules', { headers: { 'X-Requested-With': 'observa' } })).json()).editable);
const btn = p.locator('.page-head button:has-text("New Alert Rule")');
ok(editable ? await btn.getAttribute('aria-disabled') === null : (await btn.getAttribute('aria-disabled') === 'true' && /UI_RULES_FILE/.test(await btn.getAttribute('title'))), `"New Alert Rule" ${editable ? 'enabled' : 'locked with the reason'} (editing ${editable ? 'on' : 'off'})`);
const rows = await p.locator('#main tbody tr').count();
await p.click('#main .chips button:has-text("Rules")'); await settle(p, 400);
ok(/tab=rules/.test(p.url()) && /range=21600/.test(p.url()) && await p.locator('#main .chips button[aria-pressed=true]').count() === 1, 'tab in URL with range, pressed state');
await p.click('#main .chips button:has-text("Active")'); await settle(p, 400);
const sw = p.locator('#main tbody input[type=checkbox]').first();
if (await sw.count()) ok(/Notifications for/.test(await sw.getAttribute('aria-label') || ''), 'Notify switch has an accessible name');
await p.waitForTimeout(6000);
await fail('**/api/alerts', 'Alertmanager is not answering');
await p.click('#refresh-btn'); await settle(p, 800);
ok(await p.locator('#main tbody tr').count() === rows && /Couldn't refresh/.test(await txt('.stale-notice')), 'refresh failure: kept + stale notice');
await p.goto(`${BASE}/alerting`); await settle(p, 1500);
ok(await p.locator('[role=alert]:has-text("Alertmanager is not answering")').count() === 1 && await p.locator('#main button:has-text("Try again")').count() === 1, 'first-load failure: cause + Try again');
await p.unroute('**/api/alerts');
await p.click('#main button:has-text("Try again")'); await settle(p, 1800);
ok(await p.locator('#main tbody tr').count() === rows, 'Try again recovers');
await p.click('#main .chips button:has-text("Notifications")'); await settle(p, 1500);
ok(await p.locator('#main table').count() === 1, 'notifications tab loads');
await p.setViewportSize({ width: 390, height: 844 }); await p.goto(`${BASE}/alerting`); await settle(p, 2000);
const fit = await p.evaluate(() => [...document.querySelectorAll('.table-wrap')].every((w) => w.scrollWidth <= w.clientWidth + 1) && document.documentElement.scrollWidth <= 391);
ok(fit, '390px: table fits');
ok(!/null|undefined/.test(await p.locator('#main').innerText()), 'no stray null text');
ok(!errors.length, `no page errors ${errors.join(' | ')}`);
summary();
await b.close();
