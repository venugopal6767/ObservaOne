// Dashboards list + dashboard view gate.
import { chromium, BASE, ok, summary, errors, login, settle, SP } from './lib.mjs';
const b = await chromium.launch();
const p = await login(b, 'admin', '', { width: 1366, height: 900 });
const fail = (pattern, msg) => p.route(pattern, (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: msg }) }));
const txt = async (sel) => (await p.locator(sel).first().textContent().catch(() => '')) || '';
await p.route('**/api/dashboards', async (r) => { await new Promise((s) => setTimeout(s, 1500)); await r.continue().catch(() => {}); });
await p.goto(`${BASE}/dashboards?range=21600`); await p.waitForTimeout(500);
ok(await p.locator('#main .skeleton').count() >= 3, 'list loading placeholders');
await settle(p, 2000); await p.unroute('**/api/dashboards');
await p.click('#main .chips button:has-text("System")'); await settle(p, 500);
ok(/tab=system/.test(p.url()) && /range=21600/.test(p.url()) && await p.locator('#main .chips button[aria-pressed=true]').count() === 1, 'tab in URL with range, pressed state');
const cards = await p.locator('.dash-card').count();
ok(cards > 0, `system dashboards: ${cards}`);
await p.waitForTimeout(6000);
await fail('**/api/dashboards', 'Database busy');
await p.click('#refresh-btn'); await settle(p, 800);
ok(await p.locator('.dash-card').count() === cards && /Couldn't refresh/.test(await txt('.stale-notice')), 'list refresh failure: kept + stale notice');
await p.goto(`${BASE}/dashboards`); await settle(p, 1200);
ok(await p.locator('[role=alert]:has-text("Database busy")').count() === 1 && await p.locator('#main button:has-text("Try again")').count() === 1, 'list first-load failure: cause + Try again');
await p.unroute('**/api/dashboards');
// open by keyboard, context kept
await p.goto(`${BASE}/dashboards?tab=system&range=21600`); await settle(p, 2000);
await p.locator('.dash-card').first().focus(); await p.keyboard.press('Enter'); await settle(p, 2500);
ok(/\/dashboards\/[^?]+\?.*range=21600/.test(p.url()), `card opens by keyboard with range (${p.url().replace(BASE, '')})`);
const view = p.url();
const panels = await p.locator('#main section.panel').count();
ok(panels > 0, `view: ${panels} panels`);
// refresh in place: no placeholders flash, a failing query keeps the chart and says so
await p.waitForTimeout(6000);
await p.route('**/api/prom/query*', (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Prometheus is not answering' }) }));
await p.click('#refresh-btn'); await p.waitForTimeout(150);
ok(await p.locator('#main section.panel .skeleton').count() === 0, 'refresh does not blank the panels');
await settle(p, 1200);
ok(await p.locator('.panel-stale').count() >= 1, 'failed panel refresh keeps the chart and says so');
ok(!/just now/.test(await p.locator('#refresh-btn').getAttribute('title')), 'all panels failed: freshness not reset');
await p.unroute('**/api/prom/query*');
await fail('**/api/dashboards/*', 'Dashboard not found');
await p.goto(view.split('?')[0]); await settle(p, 1200);
ok(await p.locator('#main button:has-text("Try again")').count() === 1 && await p.locator('#main a:has-text("All")').count() >= 1, 'view failure: Try again + way back');
await p.unroute('**/api/dashboards/*');
await p.click('#main a:has-text("All")'); await settle(p, 1500);
ok(/\/dashboards(\?|$)/.test(p.url()), '"All" returns to the list');
await p.setViewportSize({ width: 390, height: 844 }); await p.goto(view); await settle(p, 2500);
ok(await p.evaluate(() => document.documentElement.scrollWidth <= 391), '390px: no sideways scroll');
ok(!/null|undefined/.test(await p.locator('#main').innerText()), 'no stray null text');
ok(!errors.length, `no page errors ${errors.join(' | ')}`);
summary();
await b.close();
