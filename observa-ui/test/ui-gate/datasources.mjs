// Data Sources gate.
import { chromium, BASE, ok, summary, errors, login, settle, SP } from './lib.mjs';
const b = await chromium.launch();
const p = await login(b, 'admin', '', { width: 1366, height: 900 });
await p.goto(`${BASE}/datasources`); await settle(p, 3000);
const rows = await p.locator('#main tbody tr').count();
ok(rows >= 5, `live: ${rows} sources`);
ok(await p.locator('#main tbody .pill:has-text("Testing")').count() === 0, 'all sources tested on open');
let tests = 0; p.on('request', (r) => { if (/\/api\/datasources\/\w+\/test/.test(r.url())) tests++; });
await p.click('#refresh-btn'); await settle(p, 2500);
ok(tests >= rows, `top-bar refresh re-tests every source (${tests})`);
tests = 0;
await p.route('**/api/datasources/*/test', async (r) => { await new Promise((s) => setTimeout(s, 800)); await r.continue().catch(() => {}); });
await p.click('.page-head button:has-text("Test all")'); await p.waitForTimeout(150);
ok(await p.locator('.page-head button:has-text("Test all")').isDisabled(), '"Test all" is disabled while testing');
await settle(p, 1500);
ok(await p.locator('.page-head button:has-text("Test all")').isEnabled(), '"Test all" enabled again after');
await p.unroute('**/api/datasources/*/test');
await p.route('**/api/datasources', (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Database busy' }) }));
await p.goto(`${BASE}/datasources`); await settle(p, 1200);
ok(await p.locator('[role=alert]:has-text("Database busy")').count() === 1 && await p.locator('#main button:has-text("Try again")').count() === 1, 'load failure: cause + Try again');
await p.unroute('**/api/datasources');
await p.click('#main button:has-text("Try again")'); await settle(p, 2500);
ok(await p.locator('#main tbody tr').count() === rows, 'Try again recovers');
await p.setViewportSize({ width: 390, height: 844 }); await p.goto(`${BASE}/datasources`); await settle(p, 2500);
const fit = await p.evaluate(() => [...document.querySelectorAll('.table-wrap')].every((w) => w.scrollWidth <= w.clientWidth + 1) && document.documentElement.scrollWidth <= 391);
ok(fit, '390px: table fits');
ok(!/null|undefined/.test(await p.locator('#main').innerText()), 'no stray null text');
ok(!errors.length, `no page errors ${errors.join(' | ')}`);
summary();
await b.close();
