// Insights gate.
import { chromium, BASE, ok, summary, errors, login, settle, SP } from './lib.mjs';
const b = await chromium.launch();
const p = await login(b, 'admin', '', { width: 1366, height: 900 });
const fail = (pattern, msg) => p.route(pattern, (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: msg }) }));
const txt = async (sel) => (await p.locator(sel).first().textContent().catch(() => '')) || '';
ok(await p.locator('.nav-item[aria-label=Insights] .nav-ai').count() === 0, 'menu no longer labels statistics as AI');
await p.route('**/api/insights/forecasts', async (r) => { await new Promise((s) => setTimeout(s, 1500)); await r.continue().catch(() => {}); });
await p.goto(`${BASE}/insights`); await p.waitForTimeout(500);
ok(await p.locator('#main .skeleton').count() >= 1, 'loading placeholders');
await settle(p, 2500); await p.unroute('**/api/insights/forecasts');
ok(/statistics/i.test(await txt('.page-head p')) && !/\bAI\b/.test(await txt('.page-head')), 'page says it is statistics');
const rows = await p.locator('#main tbody tr').count();
ok(rows > 0, `forecasts: ${rows} rows`);
await p.locator('#main tbody tr.clickable').first().focus(); await p.keyboard.press('Enter'); await settle(p, 600);
ok(await p.locator('#main tr.expand canvas').count() === 1 && await p.locator('#main tr[aria-expanded=true]').count() === 1, 'forecast row opens by keyboard');
await p.click('.tabs >> text=Anomalies'); await settle(p, 2500);
await p.selectOption('#main select[aria-label=Sensitivity]', 'high'); await settle(p, 2500);
ok(/tab=anomalies/.test(p.url()) && /sensitivity=high/.test(p.url()), 'tab and sensitivity in URL');
await p.goto(p.url()); await settle(p, 2500);
ok(await p.locator('#main select[aria-label=Sensitivity]').inputValue() === 'high', 'restored from the URL');
await p.waitForTimeout(6000);
await fail('**/api/insights/anomalies*', 'Prometheus is not answering');
const before = await p.locator('#main tbody tr').count();
await p.click('#refresh-btn'); await p.waitForTimeout(150);
ok(await p.locator('#main .skeleton').count() === 0, 'refresh does not blank the page');
await settle(p, 800);
ok(await p.locator('#main tbody tr').count() === before && /Couldn't refresh/.test(await txt('.stale-notice')), 'refresh failure: kept + stale notice');
await p.goto(`${BASE}/insights?tab=anomalies`); await settle(p, 1500);
ok(await p.locator('[role=alert]:has-text("Prometheus is not answering")').count() === 1 && await p.locator('#main button:has-text("Try again")').count() === 1, 'first-load failure: cause + Try again');
await p.unroute('**/api/insights/anomalies*');
await p.setViewportSize({ width: 390, height: 844 }); await p.goto(`${BASE}/insights`); await settle(p, 2500);
const fit = await p.evaluate(() => [...document.querySelectorAll('.table-wrap')].every((w) => w.scrollWidth <= w.clientWidth + 1) && document.documentElement.scrollWidth <= 391);
ok(fit, '390px: table fits');
ok(!/null|undefined/.test(await p.locator('#main').innerText()), 'no stray null text');
ok(!errors.length, `no page errors ${errors.join(' | ')}`);
summary();
await b.close();
