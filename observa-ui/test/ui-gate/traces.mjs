// Traces + Trace detail gate.
import { chromium, BASE, ok, summary, errors, login, settle, SP } from './lib.mjs';
const OUT = process.env.OUT || 'after';
const b = await chromium.launch();
const p = await login(b, 'admin', '', { width: 1366, height: 900 });
const fail = (pattern, msg) => p.route(pattern, (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: msg }) }));
const txt = async (sel) => (await p.locator(sel).first().textContent().catch(() => '')) || '';
await p.route('**/api/traces?*', async (r) => { await new Promise((s) => setTimeout(s, 1500)); await r.continue().catch(() => {}); });
await p.goto(`${BASE}/traces?q=&range=21600`); await p.waitForTimeout(500);
ok(await p.locator('#main .skeleton').count() >= 1, 'loading placeholder');
await settle(p, 2000); await p.unroute('**/api/traces?*');
const rows = await p.locator('#main tbody tr').count();
ok(rows > 0, `live: ${rows} traces`);
ok(/range=21600/.test(p.url()), 'range in URL');
await p.waitForTimeout(6000);
await fail('**/api/traces?*', 'Tempo is not answering');
await p.click('#refresh-btn'); await settle(p, 800);
ok(await p.locator('#main tbody tr').count() === rows && /Couldn't refresh/.test(await txt('.stale-notice')), 'refresh failure: list kept + stale notice');
await p.goto(`${BASE}/traces`); await settle(p, 1200);
ok(await p.locator('[role=alert]:has-text("Tempo is not answering")').count() === 1 && await p.locator('#main button:has-text("Try again")').count() === 1, 'first-load failure: cause + Try again');
await p.unroute('**/api/traces?*');
await p.click('#main button:has-text("Try again")'); await settle(p, 1800);
ok(await p.locator('#main tbody tr').count() > 0, 'Try again recovers');
// detail + context
await p.goto(`${BASE}/traces?range=21600`); await settle(p, 1800);
await p.locator('#main tbody tr').first().click(); await settle(p, 1800);
const detail = p.url();
ok(/\/traces\/[0-9a-f]+\?.*range=21600/.test(detail), 'trace keeps range');
await p.click('.tabs >> text=Spans'); await settle(p, 500);
ok(/tab=spans/.test(p.url()) && /range=21600/.test(p.url()), 'tab keeps range');
const svcLink = await p.locator('#main a[href*="/services/"]').first().getAttribute('href').catch(() => null);
ok(!svcLink || svcLink.includes('range=21600'), `service link keeps range (${svcLink})`);
await p.click('.detail-head a.back'); await settle(p, 1500);
ok(/\/traces\?.*range=21600/.test(p.url()), 'back arrow returns to Traces with range');
await p.goBack(); await settle(p, 1500);
ok(/\/traces\/[0-9a-f]+/.test(p.url()), 'browser Back returns to the trace');
await fail('**/api/traces/*', 'Tempo is not answering');
await p.goto(detail.split('?')[0]); await settle(p, 1200);
await p.screenshot({ path: `${SP}/gate/${OUT}/state-trace-error.png` });
ok(await p.locator('#main button:has-text("Try again")').count() === 1 && await p.locator('.detail-head a.back').count() === 1, 'detail failure: Try again + back');
await p.unroute('**/api/traces/*');
await p.click('#main button:has-text("Try again")'); await settle(p, 1500);
ok(await p.locator('.kpi').count() >= 4, 'detail Try again recovers');
// phone
await p.setViewportSize({ width: 390, height: 844 }); await p.goto(`${BASE}/traces`); await settle(p, 2000);
const fit = await p.evaluate(() => [...document.querySelectorAll('.table-wrap')].every((w) => w.scrollWidth <= w.clientWidth + 1) && document.documentElement.scrollWidth <= 391);
ok(fit, '390px: table fits');
ok(!/null|undefined/.test(await p.locator('#main').innerText()), 'no stray null text');
ok(!errors.length, `no page errors ${errors.join(' | ')}`);
summary();
await b.close();
